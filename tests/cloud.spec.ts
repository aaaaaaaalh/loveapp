test('failed and slow saves preserve input, block duplicate submits and never announce success early', async ({ page }) => {
  const backend = createCloudMock()
  await backend.attach(page)
  await login(page)
  await navigate(page, '留言')
  await page.getByRole('button', { name: '写一条留言' }).click()
  await page.getByLabel('想说的话').fill('失败时要保留的文字')
  backend.failNext('/rest/v1/letters')
  await page.getByRole('button', { name: '发布留言', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('保存失败')
  await expect(page.getByLabel('想说的话')).toHaveValue('失败时要保留的文字')
  expect(backend.rows.letters).toHaveLength(0)
  backend.holdLetters()
  await page.getByRole('button', { name: '发布留言', exact: true }).click()
  await expect(page.getByRole('button', { name: '正在保存…' })).toBeDisabled()
  await expect(page.getByRole('button', { name: '关闭弹窗' })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('dialog').locator('form').evaluate(form => form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })))
  expect(backend.requests.filter(request => request.path === '/rest/v1/letters' && request.method === 'POST')).toHaveLength(2)
  backend.releaseLetters()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.letter-card')).toHaveCount(1)
})

