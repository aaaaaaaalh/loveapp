test('realtime updates and fallback refresh handle changes without a page reload', async ({ page }) => {
  const backend = createCloudMock()
  await backend.attach(page)
  await page.clock.install()
  await login(page)
  await navigate(page, '留言')
  await expect(page.getByText(/实时同步已连接/)).toBeAttached()
  const row = { id: 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb', space_id: backend.spaceId, author_id: backend.ids.partner, content: '另一位成员刚写的留言', created_at: new Date().toISOString(), tone: 'rose' }
  backend.rows.letters.push(row)
  backend.broadcast('letters', row, 'INSERT')
  await expect(page.locator('.letter-card')).toContainText('另一位成员刚写的留言')
  backend.rows.letters = []
  await page.clock.fastForward(15_100)
  await expect(page.locator('.letter-card')).toHaveCount(0)
})

